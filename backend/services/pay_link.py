"""Resolve the customer-facing payment link based on the active provider.

Two modes controlled by setting `payment_link_provider`:
  - "infinitepay" (default): returns the local WhatsFlow page URL (`{base}/pay/{id}`).
    That page shows plan selection and generates an InfinitePay checkout on demand.
  - "painel": returns the pagme.xyz URL directly generated by painel.fun's
    `GET /api/payments/payment-link/client/{user_id}`. Customer pays there and
    painel renews internally — no /renew call, no webhook processing on our side.

The painel-generated links are cached in-memory for 30min per user_id to avoid
hammering the painel API on every notification burst.
"""
import asyncio
import logging
import time

from database import get_setting

logger = logging.getLogger(__name__)

# {user_id: (url, expires_at_epoch)}
_link_cache: dict[str, tuple[str, float]] = {}
_CACHE_TTL_SECONDS = 5 * 60  # 5 min — short enough to recover quickly if a link goes stale


def _cache_get(user_id: str) -> str | None:
    entry = _link_cache.get(str(user_id))
    if not entry:
        return None
    url, exp = entry
    if time.time() > exp:
        _link_cache.pop(str(user_id), None)
        return None
    return url


def _cache_set(user_id: str, url: str) -> None:
    _link_cache[str(user_id)] = (url, time.time() + _CACHE_TTL_SECONDS)


def clear_cache() -> None:
    """Called by tests or when the admin changes the provider setting."""
    _link_cache.clear()


async def resolve_pay_link(painel_user_id: str | int, fallback_local_url: str) -> str:
    """Return the correct payment link for the currently active provider."""
    provider = (await get_setting("payment_link_provider") or "infinitepay").strip().lower()
    logger.info(
        "resolve_pay_link: user_id=%s provider=%s fallback=%s",
        painel_user_id, provider, fallback_local_url,
    )
    if provider != "painel":
        return fallback_local_url

    user_id = str(painel_user_id).strip()
    if not user_id or not user_id.isdigit():
        logger.warning(
            "resolve_pay_link: user_id=%r is not numeric — falling back to local URL",
            painel_user_id,
        )
        return fallback_local_url

    cached = _cache_get(user_id)
    if cached:
        logger.info("resolve_pay_link: HIT cache for %s → %s", user_id, cached)
        return cached

    try:
        from services import painel
        data = await painel.get_client_payment_link(user_id)
        url = data.get("url")
        if url:
            _cache_set(user_id, url)
            logger.info("resolve_pay_link: painel API returned %s for user=%s", url, user_id)
            return url
        logger.warning("resolve_pay_link: painel returned no url — data=%s", data)
    except Exception as e:
        logger.warning(
            "resolve_pay_link: painel lookup FAILED for user_id=%s: %s "
            "(falling back to local URL)", user_id, e,
        )

    return fallback_local_url
